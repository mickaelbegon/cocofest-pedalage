def test_json_csv_writer_leaves_invalid_metric_cells_empty(tmp_path):
    source = tmp_path / "rho.npz"
    reduced = tmp_path / "reduced.npz"
    _write_archive(source)
    reduced.write_bytes(b"reduced-test-profile")
    report = _build(source, reduced, anchors=(6,), horizons=(1, 2))
    json_output = tmp_path / "report.json"
    csv_output = tmp_path / "report.csv"

    write_rho_retrospective_validation(json_output, csv_output, report)

    loaded = json.loads(json_output.read_text())
    assert loaded == report
    assert "NaN" not in json_output.read_text()
    with csv_output.open(newline="") as stream:
        rows = list(csv.DictReader(stream))
    assert len(rows) == 2
    assert rows[0]["status"] == "valid"
    assert rows[0]["A_rmse"]
    assert rows[1]["status"] == "censored_target_unavailable"
    assert rows[1]["A_rmse"] == ""
