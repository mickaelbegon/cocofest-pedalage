def test_intermediate_policy_excursion_is_not_hidden_by_exact_final_return(tmp_path):
    source = tmp_path / "rho.npz"
    reduced = tmp_path / "reduced.npz"
    _write_archive(
        source,
        shifted_policy_cycle=2,
        shifted_policy_delta=1e-5,
    )
    reduced.write_bytes(b"reduced-test-profile")
    threshold = 0.5 * 1e-5 / (0.0006 - 0.000131405)

    report = _build(
        source,
        reduced,
        anchors=(1,),
        horizons=(2,),
        scientific_criteria={
            "minimum_valid_anchors_per_horizon": 1,
            "maximum_A_rest_normalized_rmse": 10.0,
            "maximum_Tau1_rest_normalized_rmse": 10.0,
            "maximum_Km_rest_normalized_rmse": 10.0,
            "maximum_utilization_rmse": 10.0,
            "maximum_policy_drift_normalized_pw_rmse": threshold,
            "maximum_policy_drift_normalized_pw_p95": 10.0,
            "minimum_critical_muscle_match_fraction": 0.0,
        },
    )

    drift = report["records"][0]["metrics"]["observed_policy_drift"]
    assert drift["per_cycle"][0]["rmse"] > 0.0
    assert drift["per_cycle"][1]["rmse"] == pytest.approx(0.0)
    assert drift["worst_over_horizon"]["rmse_cycle_index"] == 2
    assert drift["worst_over_horizon"]["rmse"] > threshold
    assert report["processing_status"] == "complete"
    assert report["scientific_validation_status"] == "failed"


def test_solver_scale_observed_pw_bound_excursion_is_accepted_but_never_clipped(tmp_path):
    source = tmp_path / "rho.npz"
    reduced = tmp_path / "reduced.npz"
    _write_archive(source)
    with np.load(source, allow_pickle=False) as archive:
        payload = {key: np.asarray(archive[key]).copy() for key in archive.files}
    payload["controls__last_pulse_width_m1"][0, 3 * 6] = 0.0006 + 5e-11
    np.savez(source, **payload)
    reduced.write_bytes(b"reduced-test-profile")

    report = _build(
        source,
        reduced,
        anchors=(1,),
        horizons=(2,),
        observed_pulse_width_tolerance_s=1e-10,
    )

    record = report["records"][0]
    assert record["status"] == "valid"
    audit = record["observed_pulse_width_audits"]["path"][-1]
    assert audit["tolerated_bound_excursion_count"] == 1
    assert audit["tolerated_bound_excursions"][0]["signed_bound_excursion_s"] == pytest.approx(
        5e-11
    )
    assert audit["clipping_applied"] is False

    rejected = _build(
        source,
        reduced,
        anchors=(1,),
        horizons=(2,),
        observed_pulse_width_tolerance_s=1e-12,
    )
    assert rejected["records"][0]["status"] == "invalid_observed_policy_path"
    assert rejected["records"][0]["metrics"] is None


def test_forecast_audit_rejects_nonfinite_utilization_and_nonphysiological_state():
    parameters = [
        {
            "muscle": "m1",
            "A_rest": 100.0,
            "Tau1_rest": 0.05,
            "Km_rest": 0.1,
        }
    ]
    forecast = {
        "feasible": True,
        "final_slow_states": [[101.0, 0.05, 0.1]],
        "last_cycle_recruitment": {
            "maximum_finite_utilization": None,
            "saturated_sample_fraction": None,
            "finite_sample_count": 0,
            "critical_location": None,
        },
    }

    audit = _forecast_outcome_audit(
        forecast,
        model_parameters=parameters,
        expected_utilization_samples=6,
    )

    assert audit["valid"] is False
    assert {reason["code"] for reason in audit["reasons"]} == {
        "non_physiological_final_slow_state",
        "non_finite_or_incomplete_predicted_utilization",
    }


def test_runner_never_scores_an_infeasible_forecast(monkeypatch, tmp_path):
    source = tmp_path / "rho.npz"
    reduced = tmp_path / "reduced.npz"
    _write_archive(source)
    reduced.write_bytes(b"reduced-test-profile")
    actual_builder = retrospective.build_rho_endurance_rollout_report

    def infeasible_builder(*args, **kwargs):
        report = actual_builder(*args, **kwargs)
        for horizon in report["horizons"]:
            horizon["feasible"] = False
            horizon["first_failure"] = {"status": "pulse_width_limit_exceeded"}
            horizon["last_cycle_recruitment"]["maximum_finite_utilization"] = None
            horizon["last_cycle_recruitment"]["saturated_sample_fraction"] = None
            horizon["last_cycle_recruitment"]["finite_sample_count"] = 0
            horizon["last_cycle_recruitment"]["critical_location"] = None
        return report

    monkeypatch.setattr(
        retrospective,
        "build_rho_endurance_rollout_report",
        infeasible_builder,
    )

    report = _build(source, reduced, anchors=(1,), horizons=(2,))

    record = report["records"][0]
    assert record["status"] == "invalid_forecast_outcome"
    assert record["metrics"] is None
    assert any(
        reason["code"] == "physiologically_infeasible_recruitment_forecast"
        for reason in record["forecast_audit"]["reasons"]
    )
    assert any(
        reason["code"] == "non_finite_or_incomplete_predicted_utilization"
        for reason in record["forecast_audit"]["reasons"]
    )


