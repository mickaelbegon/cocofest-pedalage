MUSCLES = ("m1", "m2")


class _ReducedDynamics:
    muscle_names = MUSCLES
    muscle_geometry = object()
    kinematics = SimpleNamespace(direction=-1)

    @staticmethod
    def muscle_relationships(theta, omega):
        assert np.isfinite(theta) and np.isfinite(omega)
        return np.array([0.90, 0.95]), np.array([1.0, 0.98]), np.array([0.02, 0.01])


def _models():
    return [
        SimpleNamespace(
            muscle_name=name,
            a_scale=4920.0 + 100.0 * index,
            tau1_rest=0.060601,
            km_rest=0.137,
            alpha_a=-0.04,
            alpha_tau1=2.1e-6,
            alpha_km=1.9e-6,
            tau_fat=127.0,
            tau2=0.001,
            pd0=0.000131405,
            pdt=0.000194138,
        )
        for index, name in enumerate(MUSCLES)
    ]


def _write_archive(
    path,
    *,
    cycles=8,
    force_scale=1.0,
    invalid_target=None,
    shifted_policy_cycle=None,
    shifted_policy_delta=0.0,
):
    stimulations = 6
    degree = 3
    points = np.asarray(ca.collocation_points(degree, "radau"))
    times = [0.0]
    for interval in range(cycles * stimulations):
        times.extend((interval + points) / stimulations)
        times.append((interval + 1.0) / stimulations)
    times = np.asarray(times)
    local_time = np.mod(times, 1.0)
    payload = {
        "states__theta": (-2.0 * np.pi * times)[None, :],
        "states__omega": np.full((1, times.size), -2.0 * np.pi),
    }
    for index, name in enumerate(MUSCLES):
        payload[f"states__F_{name}"] = (
            force_scale
            * (8.0 + index + (1.0 + 0.2 * index) * np.cos(2.0 * np.pi * local_time))
        )[None, :]
        payload[f"states__Cn_{name}"] = (
            0.40 + 0.02 * np.sin(2.0 * np.pi * local_time)
        )[None, :]
        # A known observed trend makes endpoint comparison unambiguous.
        payload[f"states__A_{name}"] = (
            4800.0 + 100.0 * index - (2.0 + index) * times
        )[None, :]
        payload[f"states__Tau1_{name}"] = (0.065 + 1e-5 * times)[None, :]
        payload[f"states__Km_{name}"] = (0.145 + 2e-5 * times)[None, :]
        pulse_widths = np.full(cycles * stimulations, 0.0003)
        if invalid_target is not None:
            first = invalid_target * stimulations
            pulse_widths[first] = 0.0007
        if shifted_policy_cycle is not None:
            first = shifted_policy_cycle * stimulations
            pulse_widths[first : first + stimulations] += shifted_policy_delta
        payload[f"controls__last_pulse_width_{name}"] = pulse_widths[None, :]
    metadata = {
        "schema": "test-rho",
        "producer_mode": "receding_horizon_concatenation",
        "cycles_per_window": cycles,
        "stimulations_per_cycle": stimulations,
        "producer_collocation_degree": degree,
        "producer_collocation_method": "radau",
        "cycle_duration_s": 1.0,
        "model_formulation": "periodic_node",
        "pulse_width_maximum_s": 0.0006,
        "activate_force_length_relationship": True,
        "activate_force_velocity_relationship": True,
        "activate_passive_force_relationship": True,
        "terminal_wheel_q_slack": 1e-6,
    }
    payload["metadata__json"] = np.asarray(json.dumps(metadata))
    np.savez(path, **payload)


def _build(source, reduced, **kwargs):
    adapter_options = {
        "force_harmonics": 2,
        "cn_harmonics": 2,
        "kinematic_harmonics": 2,
        # Synthetic F is prescribed analytically rather than generated by
        # the Ding ODE; dedicated adapter tests cover these independent gates.
        "collocation_force_ode_tolerance_n_per_s": 1e9,
        "midpoint_force_ode_tolerance_n_per_s": 1e9,
        "midpoint_pulse_width_error_tolerance_s": 1.0,
        "muscle_models": _models(),
        "reduced_dynamics": _ReducedDynamics(),
    }
    adapter_options.update(kwargs.pop("adapter_options", {}))
    scientific_criteria = kwargs.pop(
        "scientific_criteria",
        {
            "minimum_valid_anchors_per_horizon": 1,
            "maximum_A_rest_normalized_rmse": 10.0,
            "maximum_Tau1_rest_normalized_rmse": 10.0,
            "maximum_Km_rest_normalized_rmse": 10.0,
            "maximum_utilization_rmse": 10.0,
            "maximum_policy_drift_normalized_pw_rmse": 10.0,
            "maximum_policy_drift_normalized_pw_p95": 10.0,
            "minimum_critical_muscle_match_fraction": 0.0,
        },
    )
    return build_rho_retrospective_validation_report(
        source,
        reduced,
        adapter_options=adapter_options,
        scientific_criteria=scientific_criteria,
        **kwargs,
    )


def test_explicit_cycle_selector_uses_requested_cycle(tmp_path):
    source = tmp_path / "rho.npz"
    _write_archive(source)

    selected, _ = select_certified_rho_cycle(source, cycle_index=3)

    assert selected.cycle_index == 3
    assert selected.start_column == 3 * 6 * 4
    assert selected.end_column == 4 * 6 * 4
    assert selected.states["theta"][selected.end_column] == -8.0 * np.pi

    with pytest.raises(ValueError, match="outside the declared range"):
        select_certified_rho_cycle(source, cycle_index=8)
    with pytest.raises(ValueError, match="must be an integer"):
        select_certified_rho_cycle(source, cycle_index=1.5)


def test_rho_only_retrospective_builds_auditable_state_and_recruitment_errors(tmp_path):
    source = tmp_path / "rho.npz"
    reduced = tmp_path / "reduced.npz"
    _write_archive(source)
    reduced.write_bytes(b"reduced-test-profile")

    report = _build(
        source,
        reduced,
        anchors=(1,),
        horizons=(2, 5),
        saturation_threshold=0.9,
    )

    assert report["processing_status"] == "complete"
    assert report["scientific_validation_status"] == "passed"
    assert report["data_policy"] == "rho_only_no_full_horizon_data"
    assert report["selection"]["indexing"] == "zero_based; forecast origin=end(k); target=end(k+H)"
    assert report["source"]["sha256"]
    assert report["reduced_profile"]["sha256"]
    assert report["record_counts"] == {"valid": 2}
    assert report["configuration"]["saturation_threshold"] == 0.9
    assert "scientific_criteria" in report["configuration"]
    assert [row["horizon_cycles"] for row in report["aggregate_metrics_by_horizon"]] == [2, 5]
    assert report["aggregate_metrics_by_horizon"][0]["metrics"]["valid_anchor_count"] == 1
    assert np.isfinite(
        report["aggregate_metrics_by_horizon"][0]["metrics"]["slow_state_errors"]["A"]["rmse"]
    )
    for record in report["records"]:
        assert record["status"] == "valid"
        assert record["target_cycle_index"] == 1 + record["horizon_cycles"]
        metrics = record["metrics"]
        assert set(metrics["slow_state_errors"]) == {"A", "Tau1", "Km"}
        assert len(metrics["slow_state_errors"]["A"]["per_muscle"]) == 2
        assert np.isfinite(metrics["slow_state_errors"]["A"]["rmse"])
        assert np.isfinite(metrics["capacity_ratio"]["minimum_error"])
        assert np.isfinite(metrics["recruitment"]["maximum_utilization_error"])
        assert isinstance(metrics["recruitment"]["critical_muscle_match"], bool)
        assert metrics["observed_policy_drift"]["worst_over_horizon"]["rmse"] == pytest.approx(
            0.0
        )
        assert metrics["observed_policy_drift"]["worst_over_horizon"][
            "p95_absolute"
        ] == pytest.approx(0.0)
        assert len(metrics["observed_policy_drift"]["per_cycle"]) == record["horizon_cycles"]
    horizon_two = report["records"][0]
    assert horizon_two["target_cycle_index"] == 3
    assert horizon_two["metrics"]["slow_state_errors"]["A"]["per_muscle"][0][
        "observed"
    ] == pytest.approx(4792.0)
    expected_utilization = -np.expm1(-(0.0003 - 0.000131405) / 0.000194138) / -np.expm1(
        -(0.0006 - 0.000131405) / 0.000194138
    )
    assert horizon_two["metrics"]["recruitment"][
        "maximum_utilization_observed"
    ] == pytest.approx(expected_utilization)


